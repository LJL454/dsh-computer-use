import { spawn } from "node:child_process";
const real = "E:/inkos/work/dsh-computer-use/native/indicator-helper/build/dsh-interaction-indicator.exe";
const child = spawn(real, [], { stdio: ["pipe","pipe","pipe"], windowsHide: true });
